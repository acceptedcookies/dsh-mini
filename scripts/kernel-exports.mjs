/**
 * 受审 kernel 清单。构建脚本只从这里生成 export { … }。
 * 后续 Phase 只许向本组追加，不许恢复 star-export。
 * 首版 = kernel-loader 点名的 6 个宿主消费符号 ∪ T-O-3 的 7 个内需符号。
 */

export const HOST_CONSUMED = [
  'createInitialSessionState',
  'createKernelSnapshot',
  'applyAction',
  'scheduleNextStep',
  'buildCheckpointFragment',
  'restoreFromFragment',
]

/** @type {{ spec: string, names: string[], enabled?: boolean }[]} */
export const KERNEL_EXPORTS = [
  {
    spec: '@haimang/agent-runtime-kernel',
    names: [
      ...HOST_CONSUMED,
      'buildStreamEventBody',
      'mapRuntimeEventToStreamKind',
      'RUNTIME_TO_STREAM_MAP',
      'isActiveTurnEpoch',
      'requireCompactContextHealthPort',
      'createAgentToolLifecycle',
      'PendingToolCallSchema',
    ],
  },
]

export function exportNames() {
  return KERNEL_EXPORTS.flatMap((group) => group.names)
}

export function renderEntry() {
  const lines = ['// GENERATED by scripts/build-kernel.mjs — build temp, not a contract']
  for (const group of KERNEL_EXPORTS) {
    lines.push(`export { ${group.names.join(', ')} } from '${group.spec}'`)
  }
  return `${lines.join('\n')}\n`
}
