export function exportNames() {
  return KERNEL_EXPORTS.flatMap((group) => group.names)
}

export function renderEntry() {
  const lines = ['// GENERATED by scripts/build-kernel.mjs — build temp, not a contract']
  for (const group of KERNEL_EXPORTS) {
    lines.push(`export { ${group.names.join(', ')} } from '${group.spec}'`)
  }
  return `${lines.join('\n')}\n`
}
