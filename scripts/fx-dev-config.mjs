// 由 .local.development.json 生成 services/fx/dev-config.ts（gitignored）。
// 旋钮（localRuntimeRoute）真源在 app.json["dsh"].localRuntimeRoute，此处镜像进 dev-config 作 fallback。
// 用法: node scripts/fx-dev-config.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(readFileSync(join(root, ".local.development.json"), "utf8"));

// 云端密钥面（gitignored）：WX_CLOUD_ENV_ID 优先于 .local.development.json 的 cloud.env_id
let envFile = {};
try {
  for (const line of readFileSync(join(root, ".env.wx.cloud"), "utf8").split("\n")) {
    const m = line.match(/^([A-Z_]+)=(.*)$/);
    if (m) envFile[m[1]] = m[2].trim();
  }
} catch { /* 文件缺失时全部走 .local.development.json */ }
const p = cfg.provider;
if (!p?.base_url || !p?.model) throw new Error(".local.development.json provider.base_url/model required");

const ROUTES = new Set(["local", "cloud", "cloud-sim"]);
let appRoute = "local";
try {
  const appJson = JSON.parse(readFileSync(join(root, "app.json"), "utf8"));
  const v = appJson?.dsh?.localRuntimeRoute;
  if (ROUTES.has(v)) appRoute = v;
} catch { /* app.json 缺失时用默认 */ }

const contextWindow = cfg.catalog?.[p.model]?.context_window ?? 256000;
const providersJson = JSON.stringify({
  [p.name]: {
    protocol: "openai-chat-completions",
    base_url: `${p.base_url}/v1`,
    auth: { type: "none" },
    model_metadata: {
      [p.model]: { context_window: contextWindow, supports_tool_use: true, supports_vision: true },
      unknown: { context_window: 256000, supports_tool_use: true, supports_vision: true },
    },
  },
});

const sim = cfg.sim ?? {};
const cloud = cfg.cloud ?? {};
const allowedModels = cfg.allowed_models ?? Object.keys(cfg.catalog ?? {});
if (!allowedModels.includes(p.model)) throw new Error(`provider.model ${p.model} 不在 allowed_models`);
const modelMeta = {};
for (const m of allowedModels) {
  modelMeta[m] = { context_window: cfg.catalog?.[m]?.context_window ?? 256000, supports_tool_use: true, supports_vision: true };
}
modelMeta.unknown = { context_window: 256000, supports_tool_use: true, supports_vision: true };

const out = `// GENERATED by scripts/fx-dev-config.mjs from .local.development.json — 勿手改，勿提交。
export const wasmPath = 'subpkg/fx/fx-core-async.wasm.br'
export const providerName = ${JSON.stringify(p.name)}
export const baseUrl = ${JSON.stringify(p.base_url)}
export const model = ${JSON.stringify(p.model)}

/** 旋钮镜像：真源 app.json["dsh"].localRuntimeRoute，仅作 require 失败时的 fallback。 */
export const route: 'local' | 'cloud' | 'cloud-sim' = ${JSON.stringify(appRoute)}
/** 本地模拟微信云端端点（dev 面）。 */
export const sim = ${JSON.stringify({ baseUrl: sim.base_url ?? "http://127.0.0.1:3426" }, null, 1)}
/** 真微信云端端点：env_id + 云托管 proxy https。 */
export const cloud = ${JSON.stringify({ envId: envFile.WX_CLOUD_ENV_ID || cloud.env_id || "", proxyUrl: cloud.proxy_url ?? "" }, null, 1)}
/** 直连 provider 的 api_key（local 模式 / sim enroll 明文用；仅存内存转发，不落 wx.storage）。 */
export const providerApiKey = ${JSON.stringify(p.api_key ?? "")}
/** enroll 时登记给代理的上游 base_url。 */
export const upstreamBaseUrl = ${JSON.stringify(`${p.base_url}/v1`)}
/** 业主裁决的支持模型白名单（sim/云代理数据面闸口径一致）。 */
export const allowedModels = ${JSON.stringify(allowedModels)}
/** allowedModels 对应的 provider model_metadata（context_window 取 catalog 快照）。 */
export const modelMeta = ${JSON.stringify(modelMeta)}

export const fxEnv: Record<string, string> = {
  FX_PROVIDER: providerName,
  FX_CONFIGURED_PROVIDERS: ${JSON.stringify(providersJson)},
  FX_MODEL: model,
}
`;
writeFileSync(join(root, "services/fx/dev-config.ts"), out);
console.log("services/fx/dev-config.ts generated:", p.base_url, p.model, "route=" + appRoute);
